// Funções utilitárias
export const getStockStatus = (item: InventoryItem): StockStatus => {
  if (item.currentStock === 0) return 'out-of-stock'
  if (item.currentStock <= item.minStock) return 'low'
  if (item.currentStock > item.maxStock * 0.8) return 'reserved'
  return 'available'
}

